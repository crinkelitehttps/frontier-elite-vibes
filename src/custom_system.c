/*
 * custom_system.c - see custom_system.h.
 *
 * Each body becomes one 64-byte record in the format of the game's own
 * hand-made systems (table L47390; read from Sol's records):
 *
 *   0  long  mass, units of 1e22 kg (Earth = 599); 0 ends the list
 *   4  long  seed (surface detail, colours, names of things on it)
 *   8  word  parent, 1-based record number (0 = none)
 *   10 word  kind (what the info screen calls it; $46 = surface starport)
 *   12 word  model (the look and the radius)
 *   14 long  orbit radius, units of 2^25 mm (33.554 km; Earth = 4458427)
 *   18 word  orbit phase, 65536 = 360 degrees; surface port: west longitude
 *   28 word  eccentricity x 1000
 *   30 word  inclination, 65536 = 360 degrees; surface port: latitude
 *   32 word  temperature, K
 *   34       name, NUL-terminated (21 characters at most: 56 follows)
 *   58 byte  spin: the rotation rate is doubled per step (Earth 1, 0 = none)
 *   59 byte  level: 0 star, 1 planet, 2 moon or orbital port, 3 surface port
 *   62 word  axial tilt, 65536 = 360 degrees
 *
 * The end record (mass 0) holds the generator's counters: byte 4 = bodies
 * (fewer than 12 lets asteroids appear, L8145e), byte 8 = starports, byte 9
 * = orbital ones. The game's copy loop (l4740c) turns mass and orbit into its
 * own number form and works out each orbital period from the parent's mass;
 * a surface port record is copied as it is.
 */
