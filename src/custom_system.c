typedef struct
{
	char name[NAME_LEN + 1];
	char parent_name[NAME_LEN + 1];
	int parent; /* 1-based, 0 = none */
	int type;
	int kind, model, spin, temp, level;
	uint32_t seed;
	double mass_kg, orbit_km, ecc, incl, phase, tilt, lat, lon;
	double radius_km; /* 0 = the model's */
} Body;

typedef struct
{
	char file[64];
	uint32_t key;
	char name[NAME_LEN + 3]; /* the system's own, "" = the game's */
	int count;
	Body bodies[BODIES_MAX];
} System;

static System systems[SYSTEMS_MAX];
